import pytest

from app.cli.import_addresses import normalize_address


def address_feature(version: str = "2021-05-24T11:52:27.0+00:00") -> dict:
    return {
        "type": "Feature",
        "geometry": {"type": "Point", "coordinates": [21.01, 52.23]},
        "properties": {
            "ID_IIP": "PL.ZIPIN.1469.EMUiA.c9104c20-b32b-4427-8101-a8601a2faf3f." + version,
            "ID_GMINY": "1465011",
            "NAZWA_ULICY": "ulica Łódzka",
            "NUMER_PORZADKOWY": "10A/12",
            "NAZWA_MIEJSCOWOSCI": "Warszawa",
            "KOD_POCZTOWY": "00-519",
            "DATA": None,
        },
    }


def test_address_identity_survives_source_version_changes() -> None:
    initial = normalize_address(address_feature())
    updated = normalize_address(address_feature("2026-10-23T09:00:00+00:00"))

    assert initial[0] == updated[0]
    assert initial[0].endswith("c9104c20-b32b-4427-8101-a8601a2faf3f")
    assert initial[-1].obj["ID_IIP"] != updated[-1].obj["ID_IIP"]
    assert initial[3] == "10A/12"
    assert initial[4] == "10a/12"
    assert "00-519" in initial[7]


def test_address_import_rejects_non_warsaw_records() -> None:
    feature = address_feature()
    feature["properties"]["ID_GMINY"] = "0000000"

    with pytest.raises(ValueError, match="Warsaw"):
        normalize_address(feature)


def test_address_import_requires_an_official_stable_identity() -> None:
    feature = address_feature()
    feature["properties"]["ID_IIP"] = "autogenerated-row-1"

    with pytest.raises(ValueError, match="ID_IIP"):
        normalize_address(feature)
